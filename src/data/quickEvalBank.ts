function shuffleArray<T>(items: T[]): T[] {
  const arr = [...items];
  for (let i = arr.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [arr[i], arr[j]] = [arr[j], arr[i]];
  }
  return arr;
}

export function generateQuickEvalQuestions(
  gradeFilter: 'all' | 5 | 6 | 7 | 8,
  count: number,
  difficulty: 'all' | 'easy' | 'medium' | 'hard'
): QuickEvalQuestion[] {
  let pool = QUICK_EVAL_BANK.filter((q) => {
    if (gradeFilter !== 'all' && q.grade !== gradeFilter) return false;
    if (difficulty !== 'all' && q.difficulty !== difficulty) return false;
    return true;
  });

  // Fallback if filtered by grade + single difficulty yields fewer items than count
  if (pool.length < count && difficulty !== 'all') {
    const extra = QUICK_EVAL_BANK.filter(
      (q) => (gradeFilter === 'all' || q.grade === gradeFilter) && !pool.some((p) => p.id === q.id)
    );
    pool = [...pool, ...shuffleArray(extra)];
  }

  // Fallback if still fewer (e.g., 15 requested for single grade with 13 questions)
  if (pool.length < count && gradeFilter !== 'all') {
    const extra = QUICK_EVAL_BANK.filter((q) => !pool.some((p) => p.id === q.id));
    pool = [...pool, ...shuffleArray(extra)];
  }

  return shuffleArray(pool).slice(0, Math.min(count, pool.length));
}
